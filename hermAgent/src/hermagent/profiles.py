"""Resolve (target, backend) from config/profiles.toml and render Hermes config.yaml."""
from __future__ import annotations

import platform
import tomllib
from dataclasses import dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
PROFILES = ROOT / "config" / "profiles.toml"
HERMES_HOME = ROOT / ".hermes-home"   # gitignored; regenerated, never hand-edited


@dataclass(frozen=True)
class Profile:
    target: str
    backend: str
    provider: str
    model: str
    base_url: str
    api_key_env: str
    toolsets: tuple[str, ...]
    approval_mode: str
    context_length: int


def load(path: Path = PROFILES) -> dict:
    return tomllib.loads(path.read_text())


def detect_target(cfg: dict, system: str | None = None, machine: str | None = None) -> str:
    system = system or platform.system()
    machine = machine or platform.machine()
    # most specific match first (more keys)
    for name, t in sorted(cfg["targets"].items(), key=lambda kv: -len(kv[1]["match"])):
        m = t["match"]
        if m.get("system") == system and m.get("machine", machine) == machine:
            return name
    raise SystemExit(f"no target matches {system}/{machine}; pass --target")


def resolve(target: str | None = None, backend: str | None = None, cfg: dict | None = None) -> Profile:
    cfg = cfg or load()
    target = target or detect_target(cfg)
    if target not in cfg["targets"]:
        raise SystemExit(f"unknown target {target!r}; choose from {sorted(cfg['targets'])}")
    backend = backend or cfg["targets"][target]["default_backend"]
    if backend not in cfg["backends"]:
        raise SystemExit(f"unknown backend {backend!r}; choose from {sorted(cfg['backends'])}")
    b = cfg["backends"][backend]
    return Profile(
        target=target, backend=backend, provider=b["provider"], model=b["model"],
        base_url=b["base_url"], api_key_env=b["api_key_env"],
        toolsets=tuple(cfg["toolsets"]), approval_mode=cfg["approval_mode"],
        context_length=int(cfg["context_length"]),
    )


def hermes_config(p: Profile) -> dict:
    model: dict = {"provider": p.provider, "default": p.model}
    if p.backend == "ollama":
        model |= {"base_url": p.base_url, "context_length": p.context_length,
                  "ollama_num_ctx": p.context_length}
    return {
        "model": model,
        "toolsets": list(p.toolsets),
        "platform_toolsets": {"cli": list(p.toolsets)},
        "approvals": {"mode": p.approval_mode, "cron_mode": "deny"},
        "terminal": {"backend": "local"},
        "memory": {"memory_enabled": False, "user_profile_enabled": False},
    }


def render(p: Profile, home: Path = HERMES_HOME) -> Path:
    home.mkdir(parents=True, exist_ok=True)
    out = home / "config.yaml"
    header = f"# GENERATED by `hagent render` for target={p.target} backend={p.backend}. Do not edit.\n"
    out.write_text(header + yaml.safe_dump(hermes_config(p), sort_keys=False))
    return out
